/* DSH1 解析器的電腦端測試：gcc -I../app_src dsh1_test.c ../app_src/dsh1.c && ./a.exe */
#include "dsh1.h"
#include <stdio.h>
#include <string.h>

static int fails;

#define CHECK(c) do { if (!(c)) { printf("FAIL line %d: %s\n", __LINE__, #c); fails++; } } while (0)

static bool parse(const char *s, dsh1_t *d)
{
    char buf[512];
    strncpy(buf, s, sizeof(buf) - 1);
    buf[sizeof(buf) - 1] = 0;
    return dsh1_parse(buf, d);
}

int main(void)
{
    dsh1_t d;

    /* 原專案文件裡的範例 */
    CHECK(parse("DSH1;42;1;140;4;5600;68;90;01:24.631;01:25.104;01:24.382;4.5;5;3;10;80;68;36;0;1;0;82;79;76;78", &d));
    CHECK(d.seq == 42 && d.running && d.speed == 140 && d.gear == '4');
    CHECK(d.rpm == 5600 && d.rpm_pct == 68 && d.redline_pct == 90);
    CHECK(d.lap_ms[0] == 84631 && d.lap_ms[1] == 85104 && d.lap_ms[2] == 84382);
    CHECK(d.fuel_laps_x10 == 45 && d.position == 5 && d.lap == 3 && d.laps_total == 10);
    CHECK(d.fuel_pct == 80 && d.throttle == 68 && d.brake == 36);
    CHECK(d.tc == 0 && d.abs == 1 && d.lap_invalid == 0);
    CHECK(d.tyre_x10[0] == 820 && d.tyre_x10[3] == 780);

    /* 公式實際輸出的格式：胎溫一位小數、可以是負的；序號超過 int32 */
    CHECK(parse("DSH1;4294967295;1;0;N;800;5;0;--;--;--;--;--;--;--;--;0;0;--;--;--;-12.5;85.3;--;100.0", &d));
    CHECK(d.seq == 4294967295u && d.gear == 'N' && d.redline_pct == 0);
    CHECK(d.lap_ms[0] == DSH1_NA && d.fuel_laps_x10 == DSH1_NA && d.position == DSH1_NA);
    CHECK(d.tc == -1 && d.tyre_x10[0] == -125 && d.tyre_x10[1] == 853 && d.tyre_x10[2] == DSH1_NA);

    /* 全部 "--"、遊戲沒在跑 */
    CHECK(parse("DSH1;7;0;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));
    CHECK(!d.running && d.gear == 0 && d.speed == DSH1_NA);

    /* 倒車檔、三位數分鐘 */
    CHECK(parse("DSH1;1;1;12;R;1500;10;90;123:05.009;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));
    CHECK(d.gear == 'R' && d.lap_ms[0] == (123 * 60 + 5) * 1000 + 9);

    /* 壞掉的行：解析失敗而且不能改到 out */
    d.speed = 999;
    CHECK(!parse("DSH1;1;1;140;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));   /* 24 欄 */
    CHECK(!parse("DSH1;1;1;140;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;", &d));/* 結尾分號 = 26 欄 */
    CHECK(!parse("DSH2;1;1;140;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d)); /* 版本 */
    CHECK(!parse("DSH1;1;2;140;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d)); /* running 只能 0/1 */
    CHECK(!parse("DSH1;1;1;140;X;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d)); /* 檔位 */
    CHECK(!parse("DSH1;1;1;140;10;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));/* 檔位兩位數 */
    CHECK(!parse("DSH1;1;1;1501;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));/* 車速超出 */
    CHECK(!parse("DSH1;1;1;;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));    /* 空欄位 */
    CHECK(!parse("DSH1;1;1;140;4;5600;101;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));/* 百分比超出 */
    CHECK(!parse("DSH1;1;1;140;4;5600;68;90;1:60.000;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));/* 60 秒 */
    CHECK(!parse("DSH1;1;1;140;4;5600;68;90;01:24.63;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d));/* 毫秒兩位 */
    CHECK(!parse("DSH1;1;1;140;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;2;--;--;--;--;--;--", &d));   /* 旗標 2 */
    CHECK(!parse("DSH1;1;1;140;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;1000.1;--;--;--", &d));/* 胎溫超出 */
    CHECK(!parse("DSH1;1;1;14a;4;5600;68;90;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--;--", &d)); /* 非數字 */
    CHECK(!parse("", &d));
    CHECK(d.speed == 999);

    printf(fails ? "%d FAILED\n" : "all passed\n", fails);
    return fails != 0;
}
